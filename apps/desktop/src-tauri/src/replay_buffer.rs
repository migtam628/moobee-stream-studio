//! Local rolling encoded replay. Retain complete GOPs, not raw frames.
//! No socket, network, external encoder or background capture.
use crate::{live_media_queue::MediaQueue,live_flv::Writer,stream_mux::Packet};
use std::{collections::VecDeque,io::Write};
const MAX_BYTES:usize=32*1024*1024;
const MAX_PACKETS:usize=4096;
fn copy(p:&Packet,timestamp_ms:u32)->Packet{Packet{kind:p.kind,timestamp_ms,payload:p.payload.clone()}}
fn key(p:&Packet)->bool{p.kind==9&&p.payload.get(..2)==Some(&[0x17,1])}
pub(crate) struct Ring{
    validator:MediaQueue,video_config:Option<Packet>,audio_config:Option<Packet>,
    packets:VecDeque<Packet>,bytes:usize,window_ms:u32,latest_video:u32,audio:bool,failed:bool,
}
impl Ring{
    pub(crate) fn new(seconds:u32,audio:bool)->Result<Self,String>{
        if !(2..=30).contains(&seconds){return Err("Replay window must be 2–30 seconds".into())}
        Ok(Self{validator:MediaQueue::default(),video_config:None,audio_config:None,packets:VecDeque::new(),bytes:0,window_ms:seconds*1000,latest_video:0,audio,failed:false})
    }
    fn discard(&mut self,n:usize){for _ in 0..n{if let Some(p)=self.packets.pop_front(){self.bytes-=p.payload.len();}}}
    fn next_key(&self)->Option<(usize,u32)>{self.packets.iter().enumerate().skip(1).find(|(_,p)|key(p)).map(|(i,p)|(i,p.timestamp_ms))}
    pub(crate) fn push(&mut self,p:Packet)->Result<(),String>{
        if self.failed{return Err("Replay buffer requires a fresh encoder epoch".into())}
        let result=self.push_inner(p);
        if result.is_err(){self.failed=true;self.packets.clear();self.bytes=0;}
        result
    }
    fn push_inner(&mut self,p:Packet)->Result<(),String>{
        if p.kind==8&&!self.audio{return Err("Unexpected replay audio".into())}
        self.validator.push(p)?;
        let p=self.validator.pop().ok_or("Missing validated replay packet")?;
        if p.payload[1]==0{
            if p.kind==9{self.video_config=Some(p)}else{self.audio_config=Some(p)}
            return Ok(())
        }
        if p.kind==9{self.latest_video=p.timestamp_ms;}
        self.bytes=self.bytes.checked_add(p.payload.len()).ok_or("Replay size overflow")?;
        self.packets.push_back(p);
        let cutoff=self.latest_video.saturating_sub(self.window_ms);
        while let Some((index,time))=self.next_key(){
            if time<=cutoff||self.bytes>MAX_BYTES||self.packets.len()>MAX_PACKETS{self.discard(index)}else{break}
        }
        if self.bytes>MAX_BYTES||self.packets.len()>MAX_PACKETS{return Err("Replay GOP exceeds bounded memory budget".into())}
        Ok(())
    }
    pub(crate) fn export<W:Write>(&self,out:W)->Result<u32,String>{
        if self.failed{return Err("Replay buffer failed".into())}
        let first=self.packets.front().filter(|p|key(p)).ok_or("No replay keyframe")?;
        let base=first.timestamp_ms;
        let config=self.video_config.as_ref().ok_or("Missing replay video configuration")?;
        let mut w=Writer::new(out,self.audio)?;
        w.append(copy(config,0))?;
        if self.audio{w.append(copy(self.audio_config.as_ref().ok_or("Missing replay audio configuration")?,0))?;}
        // Audio generated by a delayed codec may arrive after the next GOP
        // but belong before its first IDR. Drop that audio and any tail ahead
        // of the last retained video timestamp. Keep stable per-track order.
        let mut media=self.packets.iter().filter(|p|p.timestamp_ms>=base&&p.timestamp_ms<=self.latest_video).collect::<Vec<_>>();
        media.sort_by_key(|p|(p.timestamp_ms,if p.kind==9{0}else{1}));
        let mut frames=0;
        for p in media{
            if p.kind==9{frames+=1;}
            w.append(copy(p,p.timestamp_ms-base))?;
        }
        w.finish()?;Ok(frames)
    }
}
#[cfg(any(target_os="macos",target_os="windows"))]
pub(crate) struct Sink{
    ring:Ring,encoder:crate::live_program_encoder::Encoder,path:std::path::PathBuf,
    audio:bool,pending:Option<image::RgbaImage>,exported:u32,
}
#[cfg(any(target_os="macos",target_os="windows"))]
impl Sink{
    pub(crate) fn open(path:&std::path::Path,width:u32,height:u32,fps:u32,kbps:u32,audio:bool,seconds:u32)->Result<Self,String>{
        Ok(Self{ring:Ring::new(seconds,audio)?,encoder:crate::live_program_encoder::Encoder::new(width,height,fps,kbps,audio)?,path:path.into(),audio,pending:None,exported:0})
    }
    pub(crate) fn append(&mut self,canvas:image::RgbaImage)->Result<(),String>{
        if self.pending.is_some()||self.exported>0{return Err("Incomplete or closed replay tick".into())}
        if self.audio{self.pending=Some(canvas);Ok(())}else{self.encode(canvas,None)}
    }
    pub(crate) fn append_audio(&mut self,pcm:&[f32])->Result<(),String>{
        let canvas=self.pending.take().ok_or("Missing replay video tick")?;self.encode(canvas,Some(pcm))
    }
    fn encode(&mut self,canvas:image::RgbaImage,pcm:Option<&[f32]>)->Result<(),String>{
        for p in self.encoder.tick(canvas.as_raw(),pcm)?{self.ring.push(p)?;}
        Ok(())
    }
    pub(crate) fn finish(&mut self)->Result<(),String>{
        if self.pending.is_some()||self.exported>0{return Err("Incomplete or already exported replay".into())}
        let mut file=std::fs::OpenOptions::new().write(true).create_new(true).open(&self.path).map_err(|_|"Could not create private replay file")?;
        self.exported=self.ring.export(&mut file)?;
        file.sync_all().map_err(|_|"Could not sync replay file")?;
        Ok(())
    }
    pub(crate) fn frames(&self)->u32{self.exported}
}
#[cfg(test)]
mod tests{
    use super::*;
    use crate::stream_mux::{avc_sequence,avc_access_unit,aac_sequence,aac_access_unit};
    fn frame(t:u32)->Packet{let idr=t%2000==0;let n=if idr{0x65}else{0x41};avc_access_unit(&[&[n,1]],t,0,idr).unwrap()}
    #[test]fn retains_gop_at_or_before_cutoff_and_rebases_audio(){
        let mut ring=Ring::new(4,true).unwrap();
        ring.push(avc_sequence(&[0x67,0x64,0,0x28],&[0x68,0xee]).unwrap()).unwrap();
        ring.push(aac_sequence()).unwrap();
        for t in (0..=10000).step_by(100){
            ring.push(frame(t)).unwrap();
            ring.push(aac_access_unit(&[1,2],t.saturating_sub(20)).unwrap()).unwrap();
        }
        assert_eq!(ring.packets.front().unwrap().timestamp_ms,6000);
        let mut data=Vec::new();assert_eq!(ring.export(&mut data).unwrap(),41);
        assert_eq!(&data[..3],b"FLV");
        // Parse tag boundaries and confirm configuration and first IDR
        // start at zero, with global nondecreasing timestamps.
        let mut pos=13;let mut previous=0;let mut first_video=false;
        while pos<data.len(){
            let size=u32::from_be_bytes([0,data[pos+1],data[pos+2],data[pos+3]])as usize;
            let time=u32::from_be_bytes([data[pos+7],data[pos+4],data[pos+5],data[pos+6]]);
            assert!(time>=previous);previous=time;
            if data[pos]==9&&data[pos+12]==1&&!first_video{assert_eq!(time,0);assert_eq!(data[pos+11],0x17);first_video=true;}
            pos+=15+size;
        }
        assert!(first_video);assert_eq!(pos,data.len());assert_eq!(previous,4000);
    }
    #[test]fn invalid_stream_and_overbudget_gop_fail_closed(){
        let mut ring=Ring::new(4,false).unwrap();assert!(ring.push(frame(0)).is_err());
        assert!(ring.export(Vec::new()).is_err());
        assert!(Ring::new(31,false).is_err());
        let mut ring=Ring::new(4,false).unwrap();
        ring.push(avc_sequence(&[0x67,0x64,0,0x28],&[0x68,0xee]).unwrap()).unwrap();
        ring.push(frame(0)).unwrap();
        assert!(ring.export(Vec::new()).is_err());
        let nal=vec![0x41;1024*1024];
        let mut failed=false;
        for t in 1..40{
            if ring.push(avc_access_unit(&[&nal],t,0,false).unwrap()).is_err(){failed=true;break}
        }
        assert!(failed);assert!(ring.packets.is_empty());
    }
}
